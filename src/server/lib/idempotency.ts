import { createHash } from "node:crypto";

import { and, eq, lt } from "drizzle-orm";
import { Effect } from "effect";
import superjson, { type SuperJSONResult } from "superjson";

import {
  type Database,
  query,
  type SqlError,
  transaction,
} from "~/server/db/database";
import { idempotencyKeys } from "~/server/db/schema";
import { now } from "~/server/lib/clock";
import { type BadRequest, badRequest } from "~/server/lib/errors";

/** How long a key replays its response before the midnight job sweeps it */
export const IDEMPOTENCY_TTL_MS = 24 * 60 * 60 * 1000;

type Call = {
  userId: string;
  /** The procedure path, so a key can't replay another procedure's result */
  procedure: string;
  /** Generated by the client once per intent; absent means no protection */
  key: string | null | undefined;
  /** The input without its key, hashed to catch a key reused for new data */
  request: unknown;
};

/** JSON with object keys sorted, so the hash ignores field order */
const stableJson = (value: unknown): string => {
  if (Array.isArray(value)) {
    return `[${value.map(stableJson).join(",")}]`;
  }

  if (value !== null && typeof value === "object") {
    const fields = Object.entries(value)
      .filter(([, field]) => field !== undefined)
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
      .map(([name, field]) => `${JSON.stringify(name)}:${stableJson(field)}`);

    return `{${fields.join(",")}}`;
  }

  return JSON.stringify(value) ?? "null";
};

const hashRequest = (request: unknown) =>
  createHash("sha256").update(stableJson(request)).digest("hex");

/**
 * Runs a create call at most once per (user, key). The key row is inserted
 * first, in the same transaction as the write: a concurrent duplicate blocks
 * on the primary key until this one finishes, then replays its stored
 * response. A failure rolls the key back with everything else, so a retry
 * runs afresh. The same key with a different request (or procedure) is
 * `idempotency_key_reused`. Without a key the call runs unchanged.
 *
 * The wrapped service keeps its own `transaction`, which nests as a
 * SAVEPOINT inside the one opened here.
 */
export const idempotent = <A, E, R>(
  call: Call,
  self: Effect.Effect<A, E, R>,
): Effect.Effect<A, E | BadRequest | SqlError, R | Database> => {
  const { key, userId, procedure } = call;

  if (!key) {
    return self;
  }

  const byKey = and(
    eq(idempotencyKeys.userId, userId),
    eq(idempotencyKeys.key, key),
  );

  return transaction(
    Effect.gen(function* () {
      const requestHash = hashRequest(call.request);
      const createdAt = yield* now;
      const claimed = yield* query((db) =>
        db
          .insert(idempotencyKeys)
          .values({ userId, key, procedure, requestHash, createdAt })
          .onConflictDoNothing()
          .returning({ key: idempotencyKeys.key }),
      );

      if (claimed.length === 0) {
        const [stored] = yield* query((db) =>
          db.select().from(idempotencyKeys).where(byKey),
        );

        if (!stored?.response) {
          // the response is written in the transaction that inserted the row
          return yield* Effect.die(
            new Error("idempotency key committed without a response"),
          );
        }

        if (
          stored.procedure !== procedure ||
          stored.requestHash !== requestHash
        ) {
          return yield* badRequest("idempotency_key_reused");
        }

        return superjson.deserialize<A>(stored.response as SuperJSONResult);
      }

      const result = yield* self;
      yield* query((db) =>
        db
          .update(idempotencyKeys)
          .set({ response: superjson.serialize(result) })
          .where(byKey),
      );

      return result;
    }),
  );
};

/** Deletes keys older than the TTL (midnight job); returns how many */
export const sweepIdempotencyKeys = Effect.fn("idempotency.sweep")(
  function* () {
    const cutoff = new Date((yield* now).getTime() - IDEMPOTENCY_TTL_MS);
    const deleted = yield* query((db) =>
      db
        .delete(idempotencyKeys)
        .where(lt(idempotencyKeys.createdAt, cutoff))
        .returning({ key: idempotencyKeys.key }),
    );

    return deleted.length;
  },
);
